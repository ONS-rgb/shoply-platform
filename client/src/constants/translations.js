export const CATEGORY_TRANSLATIONS = {
  'Téléphones': { fr: 'Téléphones', ar: 'الهواتف', en: 'Phones' },
  'Ordinateurs': { fr: 'Ordinateurs', ar: 'الحواسيب', en: 'Computers' },
  'Vêtements': { fr: 'Vêtements', ar: 'الملابس', en: 'Clothing' },
  'Maison': { fr: 'Maison & Déco', ar: 'المنزل والديكور', en: 'Home & Living' },
  'Sport': { fr: 'Sport & Loisirs', ar: 'الرياضة والترفيه', en: 'Sports & Outdoors' }
};

export const translateCategory = (catName, lang = 'fr') => {
  if (!catName) return '';
  const match = CATEGORY_TRANSLATIONS[catName];
  if (match && match[lang]) return match[lang];
  return catName;
};
